#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export function renderHarnessDocs(makefile, packageJson) {
  const targets = [...makefile.matchAll(/^([A-Za-z0-9_.-]+):(?:\s|$)/gm)]
    .map((match) => match[1])
    .filter((target) => target !== ".PHONY");
  const scripts = Object.keys(packageJson.scripts ?? {});
  const targetSet = new Set(targets);
  const rows = targets.map((target) => [
    `\`make ${target}\``,
    scripts.includes(target) ? `\`npm run ${target}\`` : "—",
  ]);
  for (const script of scripts) {
    if (!targetSet.has(script)) {
      rows.push(["—", `\`npm run ${script}\``]);
    }
  }

  return [
    "# Harness Command Reference",
    "",
    "<!-- Generated by `npm run harness-docs`; do not edit by hand. -->",
    "",
    "| Make target | npm script |",
    "|---|---|",
    ...rows.map(([make, npm]) => `| ${make} | ${npm} |`),
    "",
  ].join("\n");
}

export function generateHarnessDocs(root = process.cwd()) {
  const makefile = readFileSync(path.join(root, "Makefile"), "utf8");
  const packageJson = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
  const outputPath = path.join(root, "docs", "HARNESS.md");
  mkdirSync(path.dirname(outputPath), { recursive: true });
  const content = renderHarnessDocs(makefile, packageJson);
  writeFileSync(outputPath, content, "utf8");
  return content;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateHarnessDocs();
}
